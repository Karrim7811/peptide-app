// Regenerate supabase/shop_seed.sql from the TS catalogue.
//
//   node scripts/generate-shop-seed.mjs
//
// src/lib/shop/catalogue.ts is the source of truth; the seed is output. Edit the
// catalogue, run this, commit both. Node 24 strips TypeScript natively, so this
// needs no build step and no extra dependency.
//
// The generator refuses to write a file containing a Janoshik report code. That
// should be impossible — the catalogue has no field for one — but the seed is
// the last artifact before data reaches a database the storefront reads, so it
// is the right place for a final check.

import { writeFileSync } from 'node:fs'
import { LOTS, PRODUCTS } from '../src/lib/shop/catalogue.ts'
import { REPORT_CODES } from '../src/lib/vial-reports.server.ts'

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (v) => (v ? `array[${v.map(q).join(', ')}]` : 'null')
const json = (v) => (v ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb` : 'null')
const num = (v) => (v === null || v === undefined ? 'null' : String(v))

const lines = [
  '-- GENERATED by scripts/generate-shop-seed.mjs — do not edit by hand.',
  '-- Source of truth: src/lib/shop/catalogue.ts',
  '--',
  '-- Idempotent: products upsert on slug, lots insert only when absent. Safe to',
  '-- re-run after a price change. Apply shop_schema.sql first.',
  '',
]

for (const p of PRODUCTS) {
  lines.push(
    'insert into public.shop_products',
    '  (slug, name, compound_id, size_value, size_unit, price_cents, blend_of, active, sort_order)',
    `values (${q(p.slug)}, ${q(p.name)}, ${q(p.compoundId)}, ${num(p.sizeValue)}, ${q(p.sizeUnit)}, ${num(p.priceCents)}, ${arr(p.blendOf)}, ${p.active}, ${num(p.sortOrder)})`,
    'on conflict (slug) do update set',
    '  name = excluded.name, price_cents = excluded.price_cents,',
    '  active = excluded.active, sort_order = excluded.sort_order;',
    '',
  )
}

for (const l of LOTS) {
  lines.push(
    'insert into public.shop_lots',
    '  (product_id, lot_code, assay_state, assay_type, purity_pct, components,',
    '   label_mg, measured_total_mg, assay_expected_at, mfg, exp, shelf_life, is_current)',
    `select p.id, ${q(l.lotCode)}, ${q(l.assayState)}, ${q(l.assayType)}, ${num(l.purityPct)}, ${json(l.components)},`,
    `       ${num(l.labelMg)}, ${num(l.measuredTotalMg)}, ${q(l.assayExpectedAt)}, ${q(l.mfg)}, ${q(l.exp)}, ${q(l.shelfLife)}, ${l.isCurrent}`,
    `from public.shop_products p where p.slug = ${q(l.productSlug)}`,
    // Keyed on the pair rather than lot_code, which is null for pending batches
    // and so cannot carry an on-conflict target.
    'and not exists (select 1 from public.shop_lots l where l.product_id = p.id',
    `  and coalesce(l.lot_code, '') = coalesce(${q(l.lotCode)}, ''));`,
    '',
  )
}

const sql = lines.join('\n')

const leaked = Object.values(REPORT_CODES).filter((code) => sql.includes(code))
if (leaked.length > 0) {
  console.error(`REFUSING TO WRITE: seed contains ${leaked.length} Janoshik report code(s).`)
  console.error('A code in a table the storefront reads publishes the supply chain. See spec D3.')
  process.exit(1)
}

writeFileSync('supabase/shop_seed.sql', sql)
console.log(`wrote ${PRODUCTS.length} products, ${LOTS.length} lots — no report codes present`)
